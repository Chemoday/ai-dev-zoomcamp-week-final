export function normalizeCycleIndex(cycleIndex) {
  const n = Number(cycleIndex)
  if (!Number.isFinite(n)) return 0
  return ((Math.trunc(n) % SWATCH_CYCLE_COUNT) + SWATCH_CYCLE_COUNT) % SWATCH_CYCLE_COUNT
}

/**
 * Returns the 4 swatches of a preset cyclically shifted by cycleIndex (0..3).
 * Only the 4 colors of this preset are permuted:
 *   cycle 0: [c0, c1, c2, c3]
 *   cycle 1: [c1, c2, c3, c0]
 *   cycle 2: [c2, c3, c0, c1]
 *   cycle 3: [c3, c0, c1, c2]
 */
export function getRotatedSwatches(preset, rawCycleIndex = 0) {
  const swatches = Array.isArray(preset?.swatches)
    ? preset.swatches
    : ['#f8f9fa', '#eff4ff', '#0f172a', '#005ac2']
  const cycle = normalizeCycleIndex(rawCycleIndex)
  if (cycle === 0) {
    return [...swatches]
  }
  return swatches.map((_, idx) => swatches[(idx + cycle) % swatches.length])
}

/**
 * Computes semantic CSS tokens for a given preset from its 4 cyclically shifted swatches:
 *   rotated[0] -> Surface / Page background (--color-surface)
 *   rotated[1] -> Card / Container background (--color-surface-container-lowest)
 *   rotated[2] -> Primary action / main accent (--color-primary)
 *   rotated[3] -> Secondary accent (--color-secondary)
 */
export function getCycledTokens(preset, rawCycleIndex = 0) {
  const cycle = normalizeCycleIndex(rawCycleIndex)
  const base = preset.tokens
  if (cycle === 0) {
    return base
  }

  const [surfaceHex, cardHex, primaryHex, secondaryHex] = getRotatedSwatches(preset, cycle)

  const sortedByLuminance = [...preset.swatches].sort((a, b) => getLuminance(a) - getLuminance(b))
  const darkestSwatch = sortedByLuminance[0]
  const lightestSwatch = sortedByLuminance[sortedByLuminance.length - 1]

  const darkInk = getLuminance(darkestSwatch) < 0.18 ? darkestSwatch : '#0f172a'
  const lightInk = getLuminance(lightestSwatch) > 0.65 ? lightestSwatch : '#f8fafc'

  const onCard = pickContrastOn(cardHex, darkInk, lightInk)
  const onSurfaceVariant = mixHex(onCard, cardHex, 0.35)
  const outline = mixHex(onCard, cardHex, 0.5)
  const outlineVariant = mixHex(cardHex, onCard, 0.18)

  const containerLow = mixHex(cardHex, surfaceHex, 0.28)
  const containerMid = mixHex(cardHex, surfaceHex, 0.5)
  const containerHigh = mixHex(cardHex, primaryHex, 0.16)
  const containerHighest = mixHex(cardHex, primaryHex, 0.26)

  const onPrimary = pickContrastOn(primaryHex, darkInk, lightInk)
  const onSecondary = pickContrastOn(secondaryHex, darkInk, lightInk)

  const primaryContainer = mixHex(primaryHex, cardHex, 0.35)
  const onPrimaryContainer = pickContrastOn(primaryContainer, darkInk, lightInk)

  const secondaryContainer = mixHex(secondaryHex, cardHex, 0.35)
  const onSecondaryContainer = pickContrastOn(secondaryContainer, darkInk, lightInk)

  return {
    ...base,
    '--color-surface': surfaceHex,
    '--color-background': surfaceHex,
    '--color-surface-bright': surfaceHex,
    '--color-surface-dim': mixHex(surfaceHex, darkInk, 0.12),
    '--color-surface-container-lowest': cardHex,
    '--color-surface-container-low': containerLow,
    '--color-surface-container': containerMid,
    '--color-surface-container-high': containerHigh,
    '--color-surface-container-highest': containerHighest,
    '--color-surface-variant': containerHighest,
    '--color-on-surface': onCard,
    '--color-on-background': pickContrastOn(surfaceHex, darkInk, lightInk),
    '--color-on-surface-variant': onSurfaceVariant,
    '--color-outline': outline,
    '--color-outline-variant': outlineVariant,
    '--color-surface-tint': primaryHex,
    '--color-primary': primaryHex,
    '--color-on-primary': onPrimary,
    '--color-primary-container': primaryContainer,
    '--color-on-primary-container': onPrimaryContainer,
    '--color-primary-fixed': containerHigh,
    '--color-primary-fixed-dim': containerHighest,
    '--color-on-primary-fixed': onCard,
    '--color-on-primary-fixed-variant': onSurfaceVariant,
    '--color-secondary': secondaryHex,
    '--color-on-secondary': onSecondary,
    '--color-secondary-container': secondaryContainer,
    '--color-on-secondary-container': onSecondaryContainer,
    '--color-secondary-fixed': secondaryContainer,
    '--color-secondary-fixed-dim': secondaryContainer,
    '--color-on-secondary-fixed': onSecondaryContainer,
    '--color-on-secondary-fixed-variant': onSecondaryContainer,
    '--color-inverse-surface': onCard,
    '--color-inverse-on-surface': cardHex,
  }
}

export function getThemePreset(themeId) {
  return THEME_PRESETS.find((p) => p.id === themeId) || THEME_PRESETS[0]
}

export function readStoredTheme() {
  try {
    if (typeof window !== 'undefined' && window.localStorage) {
      const saved = window.localStorage.getItem(THEME_STORAGE_KEY)
      if (saved && THEME_PRESETS.some((p) => p.id === saved)) {
        return saved
      }
    }
  } catch {
    // Ignore storage read errors
  }
  return DEFAULT_THEME_ID
}

export function readStoredThemeCyclesMap() {
  try {
    if (typeof window !== 'undefined' && window.localStorage) {
      const raw = window.localStorage.getItem(THEME_CYCLES_MAP_STORAGE_KEY)
      if (raw) {
        const parsed = JSON.parse(raw)
        if (parsed && typeof parsed === 'object') {
          const normalized = {}
          for (const [k, v] of Object.entries(parsed)) {
            normalized[k] = normalizeCycleIndex(v)
          }
          return normalized
        }
      }
    }
  } catch {
    // Ignore storage read errors
  }
  return {}
}

export function writeStoredThemeCyclesMap(cyclesMap) {
  try {
    if (typeof window !== 'undefined' && window.localStorage) {
      window.localStorage.setItem(THEME_CYCLES_MAP_STORAGE_KEY, JSON.stringify(cyclesMap || {}))
    }
  } catch {
    // Ignore storage write errors
  }
}

export function readStoredThemeCycle(themeId = readStoredTheme()) {
  const map = readStoredThemeCyclesMap()
  return normalizeCycleIndex(map[themeId] ?? DEFAULT_CYCLE_INDEX)
}

export function applyTheme(themeId, rawCycleIndex) {
  const preset = getThemePreset(themeId)
  const map = readStoredThemeCyclesMap()
  const cycleIndex =
    rawCycleIndex !== undefined
      ? normalizeCycleIndex(rawCycleIndex)
      : normalizeCycleIndex(map[preset.id] ?? DEFAULT_CYCLE_INDEX)

  const tokens = getCycledTokens(preset, cycleIndex)

  if (typeof document !== 'undefined' && document.documentElement) {
    const root = document.documentElement
    root.dataset.theme = preset.id
    root.dataset.themeCycle = String(cycleIndex)
    for (const [token, value] of Object.entries(tokens)) {
      root.style.setProperty(token, value)
    }
  }
  try {
    if (typeof window !== 'undefined' && window.localStorage) {
      window.localStorage.setItem(THEME_STORAGE_KEY, preset.id)
      map[preset.id] = cycleIndex
      writeStoredThemeCyclesMap(map)
    }
  } catch {
    // Ignore storage write errors
  }
  return preset.id
}
